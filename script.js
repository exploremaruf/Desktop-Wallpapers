const gallery = document.getElementById('gallery');
const countText = document.getElementById('countText');
const searchInput = document.getElementById('searchInput');
const previewDialog = document.getElementById('previewDialog');
const previewImage = document.getElementById('previewImage');
const previewDownload = document.getElementById('previewDownload');
const closePreview = document.getElementById('closePreview');

function openPreview(file) {
  previewImage.src = file;
  previewImage.alt = file;
  previewDownload.href = file;
  previewDownload.download = file;
  previewDownload.textContent = `Download ${file}`;
  previewDialog.showModal();
}

function createCard(file) {
  const article = document.createElement('article');
  article.className = 'card';

  const image = document.createElement('img');
  image.src = file;
  image.alt = file;
  image.loading = 'lazy';
  image.addEventListener('click', () => openPreview(file));

  const content = document.createElement('div');
  content.className = 'card-content';

  const name = document.createElement('p');
  name.className = 'filename';
  name.textContent = file;

  const downloadLink = document.createElement('a');
  downloadLink.className = 'download-btn';
  downloadLink.href = file;
  downloadLink.download = file;
  downloadLink.textContent = 'Download';

  content.append(name, downloadLink);
  article.append(image, content);

  return article;
}

function render(filter = '') {
  const term = filter.trim().toLowerCase();
  const filtered = wallpapers.filter((file) => file.toLowerCase().includes(term));

  gallery.innerHTML = '';

  if (!filtered.length) {
    const empty = document.createElement('p');
    empty.className = 'empty';
    empty.textContent = 'No wallpapers found.';
    gallery.appendChild(empty);
  } else {
    const fragment = document.createDocumentFragment();
    filtered.forEach((file) => fragment.appendChild(createCard(file)));
    gallery.appendChild(fragment);
  }

  countText.textContent = `${filtered.length} of ${wallpapers.length} wallpapers`;
}

searchInput.addEventListener('input', (event) => render(event.target.value));
closePreview.addEventListener('click', () => previewDialog.close());
previewDialog.addEventListener('click', (event) => {
  const rect = previewDialog.getBoundingClientRect();
  const clickedInDialog =
    event.clientX >= rect.left &&
    event.clientX <= rect.right &&
    event.clientY >= rect.top &&
    event.clientY <= rect.bottom;

  if (!clickedInDialog) {
    previewDialog.close();
  }
});

render();
